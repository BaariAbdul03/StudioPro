    await openLibrary.click()
    await library.getByRole('button', { name: 'Blocks', exact: true }).click()
    await library.getByRole('button', { name: 'Add Heading', exact: true }).click()
    await expect(library).toBeHidden()
    await openLibrary.click()
    await library.getByRole('button', { name: 'Symbols', exact: true }).click()
    await library.getByRole('button', { name: 'Button group', exact: true }).click()
    await library.getByRole('button', { name: 'Insert linked Button group', exact: true }).click()
    const instances = canvas.locator('[data-studio-preset="buttons"]')
    await expect(instances).toHaveCount(2)

    await page.getByRole('button', { name: 'Properties', exact: true }).click()
    await expect(library).toBeHidden()
    await properties.getByRole('button', { name: 'Style Properties' }).click()
    await properties.getByLabel('Width unit').selectOption('px')
    await properties.getByLabel('Width', { exact: true }).fill('180')
    await expect(instances.first()).toHaveCSS('width', '180px')
